#!/usr/bin/env python3
"""Lists the methods of the Direct3D 9 interfaces, in vtable order, with their stdcall argument word counts.

The counts come from the MinGW-w64 d3d9.h: every parameter of these interfaces is a 32-bit word, so a method takes its parameter
count plus the object pointer.

usage: generate-d3d9-vtables.py D3D9_HEADER OUTPUT.inc
"""

import re
import sys

WANTED = ["IDirect3D9", "IDirect3DDevice9", "IDirect3DTexture9", "IDirect3DSurface9", "IDirect3DVertexBuffer9", "IDirect3DIndexBuffer9",
          "IDirect3DSwapChain9", "IDirect3DVertexDeclaration9", "IDirect3DStateBlock9"]
BASE = {"IDirect3D9": None, "IDirect3DDevice9": None, "IDirect3DSwapChain9": None, "IDirect3DVertexDeclaration9": None,
        "IDirect3DStateBlock9": None, "IDirect3DResource9": None, "IDirect3DBaseTexture9": "IDirect3DResource9",
        "IDirect3DSurface9": "IDirect3DResource9", "IDirect3DVertexBuffer9": "IDirect3DResource9",
        "IDirect3DIndexBuffer9": "IDirect3DResource9", "IDirect3DTexture9": "IDirect3DBaseTexture9"}
UNKNOWN = [("QueryInterface", 3), ("AddRef", 1), ("Release", 1)]


def methods(text, interface):
    start = text.index(f"DECLARE_INTERFACE_IID_({interface},")
    end = text.index("#undef INTERFACE", start)
    body = text[start:end]
    found = []
    for match in re.finditer(r"STDMETHOD(?:_\(\s*[^,)]+,\s*(\w+)\s*\)|\((\w+)\))\s*\(([^;]*?)\)\s*PURE;", body, re.S):
        name, params = match.group(1) or match.group(2), match.group(3).strip()
        params = re.sub(r"^THIS_?", "", params).strip()
        count = 0
        if params:
            depth = 0
            count = 1
            for character in params:
                depth += character in "(<"
                depth -= character in ")>"
                if character == "," and depth == 0:
                    count += 1
        found.append((name, count + 1))
    return [item for item in found if item[0] not in ("QueryInterface", "AddRef", "Release")]


def table(text, interface):
    chain = []
    cursor = interface
    while cursor:
        chain.append(cursor)
        cursor = BASE.get(cursor)
    result = list(UNKNOWN)
    for name in reversed(chain):
        result += methods(text, name)
    return result


def main():
    text = open(sys.argv[1]).read()
    with open(sys.argv[2], "w") as out:
        out.write("// Generated by scripts/generate-d3d9-vtables.py from the MinGW-w64 d3d9.h; do not edit.\n")
        for interface in WANTED:
            out.write(f"// {interface}\n")
            for index, (name, words) in enumerate(table(text, interface)):
                out.write(f"{{\"{interface}\", \"{name}\", {index}, {words}}},\n")


if __name__ == "__main__":
    main()
