// GenerateOleaut32 creates the synthetic oleaut32.dll with correct ordinal exports.
func GenerateOleaut32(mem *mmu.MMU) *SynthPE {
	names := make([]string, len(Oleaut32Exports))
	for i, e := range Oleaut32Exports {
		names[i] = e.Name
	}
	synth := GenerateSynthDLL(mem, "oleaut32.dll", names, oleaut32IDBase)
	// Override ExportOrds with correct Wine/ReactOS ordinals so that
	// ordinal-only imports (e.g. from notepad++.exe) resolve properly.
	synth.ExportOrds = make(map[uint16]uint64)
	for _, e := range Oleaut32Exports {
		if addr, ok := synth.Exports[e.Name]; ok {
			synth.ExportOrds[e.Ordinal] = addr
		}
	}
	return synth
}
