package win32

// Paint cycle helpers - ported from ReactOS
// win32ss/user/user32/windows/paint.c
//
// In ReactOS the actual dirty-region tracking lives in win32k (kernel) via
// hrgnUpdate on the WND struct.  Here we implement the same semantics using
// our per-HWND dirty rect in the Manager.

// InvalidateRect marks the window's update region dirty.
// rect == nil → entire client area.
// Mirrors ReactOS NtUserInvalidateRect / the public InvalidateRect wrapper.
func InvalidateRect(hwnd uint64, rect *Rect) {
	Global.Invalidate(hwnd, rect)
}

// ValidateRect clears the dirty flag for a window.
func ValidateRect(hwnd uint64) {
	Global.Validate(hwnd)
}

// GetUpdateRect returns the bounding rect of the current update region in
// client coordinates.  Returns (rect, true) when dirty, (zero, false) when
// clean - matching ReactOS behaviour.
func GetUpdateRect(hwnd uint64) (Rect, bool) {
	return Global.GetUpdateRect(hwnd)
}

// BeginPaintInfo is the data filled by BeginPaint.
// Mirrors the relevant fields of PAINTSTRUCT:
//   - Dirty   → fErase (we set false: caller draws everything)
//   - PaintRC → rcPaint in client coordinates
type BeginPaintInfo struct {
	Dirty   bool
	PaintRC Rect
}

// BeginPaint fills BeginPaintInfo and clears the dirty flag.
// The caller should use PaintRC to set up its PAINTSTRUCT.
// Mirrors ReactOS: BeginPaint → NtUserBeginPaint.
func BeginPaint(hwnd uint64) BeginPaintInfo {
	rc, dirty := Global.GetUpdateRect(hwnd)
	if !dirty {
		// No update region: use entire client area (matches Windows behaviour
		// when a WM_PAINT is generated by UpdateWindow on a non-dirty window).
		cr := GetClientRect(hwnd)
		rc = cr
	}
	Global.Validate(hwnd)
	return BeginPaintInfo{
		Dirty:   false,
		PaintRC: rc,
	}
}

// EndPaint is called after painting; currently a no-op since we don't need
// to release an OS region handle.
func EndPaint(hwnd uint64) {}

// RedrawWindow invalidates the window (or a sub-rect) and optionally
// triggers an immediate WM_PAINT via UpdateWindow semantics.
// Flags mirror the RDW_* constants (subset implemented).
const (
	RDW_INVALIDATE      = 0x0001
	RDW_INTERNALPAINT   = 0x0002
	RDW_ERASE           = 0x0004
	RDW_VALIDATE        = 0x0008
	RDW_NOINTERNALPAINT = 0x0010
	RDW_NOERASE         = 0x0020
	RDW_NOCHILDREN      = 0x0040
	RDW_ALLCHILDREN     = 0x0080
	RDW_UPDATENOW       = 0x0100
	RDW_ERASENOW        = 0x0200
	RDW_FRAME           = 0x0400
	RDW_NOFRAME         = 0x0800
)

func RedrawWindow(hwnd uint64, rect *Rect, flags uint32) bool {
	if flags&RDW_INVALIDATE != 0 {
		Global.Invalidate(hwnd, rect)
	}
	if flags&RDW_VALIDATE != 0 {
		Global.Validate(hwnd)
	}
	return true
}
